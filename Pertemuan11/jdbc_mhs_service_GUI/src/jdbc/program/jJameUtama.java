    private void jButtonGetAllActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonGetAllActionPerformed
        if (service.isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this, "Tabel mahasiswa kosong!");
        } else {
            refreshList();
        }
    }//GEN-LAST:event_jButtonGetAllActionPerformed

    private void jButtonAddNamaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonAddNamaActionPerformed
        String nama = jTextFieldNama.getText().trim();
        if (nama.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Nama tidak boleh kosong!");
            return;
        }
        Mahasiswa mhs = service.makeMhsObject();
        mhs.setNama(nama);
        service.add(mhs);
        refreshList();
        jTextFieldNama.setText("");
    }//GEN-LAST:event_jButtonAddNamaActionPerformed

    private void jButtonEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonEditActionPerformed
        String idStr = jTextFieldIDEdit.getText().trim();
        String nama  = jTextFieldNamaEdit.getText().trim();
        
        if (idStr.isEmpty() || nama.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "ID dan Nama harus diisi!");
            return;
        }
        try {
            int id = Integer.parseInt(idStr);
            Mahasiswa cek = service.getById(id);
            if (cek == null) {
                javax.swing.JOptionPane.showMessageDialog(this, "ID " + id + " tidak ditemukan!");
                return;
            }
            Mahasiswa mhs = new Mahasiswa(id, nama);
            service.update(mhs);
            refreshList();
            jTextFieldIDEdit.setText("");
            jTextFieldNamaEdit.setText("");
        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "ID harus berupa angka!");
        }
    }//GEN-LAST:event_jButtonEditActionPerformed

    private void jButtonHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonHapusActionPerformed
        String idStr = jTextFieldIDHapus.getText().trim();
        
        if (idStr.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "ID harus diisi!");
            return;
        }
        try {
            int id = Integer.parseInt(idStr);
            Mahasiswa cek = service.getById(id);
            if (cek == null) {
                javax.swing.JOptionPane.showMessageDialog(this, "ID " + id + " tidak ditemukan!");
                return;
            }
            service.delete(id);
            refreshList();
            jTextFieldIDHapus.setText("");
            jTextFieldNamaHapus.setText("");
        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "ID harus berupa angka!");
        }
    }//GEN-LAST:event_jButtonHapusActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        int konfirmasi = javax.swing.JOptionPane.showConfirmDialog(
            this,
            "Yakin ingin reset indeks? Semua data akan dihapus!",
            "Konfirmasi Reset",
            javax.swing.JOptionPane.YES_NO_OPTION
        );
        if (konfirmasi == javax.swing.JOptionPane.YES_OPTION) {
            service.indexReset();
            modelID.clear();
            modelNama.clear();
            javax.swing.JOptionPane.showMessageDialog(this, "Index di reset ke 1");
        }

    }//GEN-LAST:event_jButton3ActionPerformed

    private void jListIDValueChanged(javax.swing.event.ListSelectionEvent evt) {//GEN-FIRST:event_jListIDValueChanged
        if (!evt.getValueIsAdjusting()) {
            int idx = jListID.getSelectedIndex();
            if (idx >= 0) {
                String id   = modelID.getElementAt(idx);
                String nama = modelNama.getElementAt(idx);
                jTextFieldIDEdit.setText(id);
                jTextFieldNamaEdit.setText(nama);
                jTextFieldIDHapus.setText(id);
                jTextFieldNamaHapus.setText(nama);
            }
        }
    }//GEN-LAST:event_jListIDValueChanged

