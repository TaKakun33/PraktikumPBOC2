    private void refreshList() {
        modelID.clear();
        modelNama.clear();
        List<Mahasiswa> list = service.getAll();
        for (Mahasiswa m : list) {
            modelID.addElement(String.valueOf(m.getId()));
            modelNama.addElement(m.getNama());
        }
    }

